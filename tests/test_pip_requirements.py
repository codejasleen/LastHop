from app.advisories import is_affected
from app.pip_requirements import parse_requirements


def test_pinned_requirements_are_positive_evidence_only():
    deps, edges = parse_requirements("urllib3==2.6.3\nrequests>=2.0\n-r more.txt\nJinja2==3.1.6 # pinned\n")
    assert [(dep.name, dep.version) for dep in deps] == [("urllib3", "2.6.3"), ("jinja2", "3.1.6")]
    assert edges == [("", "urllib3"), ("", "jinja2")]
    assert is_affected("2.6.3", ">=1.26.0 <2.8.0", "PyPI") is True
    assert is_affected("2.8.0", ">=1.26.0 <2.8.0", "PyPI") is False


def test_hashed_pip_compile_output_is_read():
    # Exact shape of open-telemetry/opentelemetry-demo src/load-generator/requirements.txt:
    # continuation lines with --hash options used to hide every pin (false "not present").
    deps, _ = parse_requirements(
        "#\n# This file is autogenerated by pip-compile with Python 3.14\n#\n"
        "bidict==0.24.1 \\\n"
        "    --hash=sha256:4dca6c17f0b01700e9f24359daa5ebabf7be022d99f4cb2a257b6af2a5076c88 \\\n"
        "    --hash=sha256:5dae8d4d79b552a71cbabc7deb25dfe8ce710b17ff41711e13010ead2abfc3e6\n"
        "    # via python-socketio\n"
        "Flask[async]==3.1.0 ; python_version >= \"3.9\" \\\n"
        "    --hash=sha256:aaaa\n"
    )
    assert {dep.name: dep.version for dep in deps} == {"bidict": "0.24.1", "flask": "3.1.0"}


def test_pinned_but_unaffected_python_version_is_a_clear_verdict():
    from app.main import _verdict
    checked = [{"package": "urllib3", "version": "2.8.0", "affected": False}]
    context = {"manager": "pip", "services": []}
    assert _verdict([], checked, context, uncertain=False)[0] == "not_affected_version"
    assert _verdict([], [], context, uncertain=False)[0] == "insufficient_evidence"  # absent: still inconclusive
    assert _verdict([], checked, context, uncertain=True)[0] == "insufficient_evidence"


def test_pip_compile_via_comments_become_real_edges():
    # Shape of GoogleCloudPlatform/microservices-demo src/emailservice/requirements.txt.
    deps, edges = parse_requirements(
        "google-api-core==2.19.0\n    # via -r requirements.in\n"
        "requests==2.32.5 \\\n    --hash=sha256:aa\n    # via\n    #   google-api-core\n    #   -r requirements.in\n"
        "urllib3==2.6.3\n    # via requests\n"
        "wrapt==1.16.0\n    # via\n    #   google-api-core\n    #   requests\n"
    )
    assert {d.name for d in deps} == {"google-api-core", "requests", "urllib3", "wrapt"}
    assert set(edges) == {("", "google-api-core"), ("", "requests"), ("google-api-core", "requests"),
                          ("requests", "urllib3"), ("google-api-core", "wrapt"), ("requests", "wrapt")}


def test_editable_installs_are_skipped():
    deps, _ = parse_requirements("-e .\nrequests==2.31.0\n")
    assert [(dep.name, dep.version) for dep in deps] == [("requests", "2.31.0")]
